export function createInitialCategories(eventType: EventType, totalBudget: number): BudgetCategory[] {
  const templates = DEFAULT_BUDGET_CATEGORIES[eventType] || DEFAULT_BUDGET_CATEGORIES.wedding;
  return templates.map((tmpl, idx) => ({
    id: `cat-${eventType}-${idx + 1}`,
    name: tmpl.name,
    allocatedPercentage: tmpl.allocatedPercentage,
    allocatedAmount: Math.round((totalBudget * tmpl.allocatedPercentage) / 100),
    color: tmpl.color,
  }));
}

